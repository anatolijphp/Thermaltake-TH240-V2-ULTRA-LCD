//! The device description Armoury Crate asks for (IAacLedDevice::GetCapability). Platform-independent so it can be
//! tested anywhere; it must stay byte-identical to the C# plugin's (aura/AuraHal.cs).

pub const LED_COUNT: u32 = 8;

/// EXTERNAL_GENERAL_RGB_LIGHTING: generic third-party device. (WATER_COOLER 0xD1000 is accepted and synced by
/// LightingService but Armoury Crate only shows known ASUS AIO models for it.)
pub const DEVICE_TYPE: u32 = 0x64000;

/// One supported effect.
struct Effect {
    id: u32,
    name: &'static str,
    customized_color: u32,
    synchronizable: u32,
    speed_levels: u32, // 0 = none
}

const EFFECTS: [Effect; 7] = [
    Effect { id: 0, name: "Manual", customized_color: 1, synchronizable: 0, speed_levels: 0 },
    Effect { id: 1, name: "Static", customized_color: 1, synchronizable: 0, speed_levels: 0 },
    Effect { id: 2, name: "Breathing", customized_color: 1, synchronizable: 1, speed_levels: 3 },
    Effect { id: 3, name: "Strobing", customized_color: 1, synchronizable: 1, speed_levels: 3 },
    Effect { id: 4, name: "Color cycle", customized_color: 0, synchronizable: 1, speed_levels: 3 },
    Effect { id: 5, name: "Rainbow", customized_color: 0, synchronizable: 1, speed_levels: 3 },
    Effect { id: 0xFF, name: "Default", customized_color: 0, synchronizable: 0, speed_levels: 0 },
];

pub fn capability_xml() -> String {
    use std::fmt::Write;
    let mut x = String::with_capacity(4096);
    x.push_str("<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"no\" ?>\n<root>\n");
    x.push_str("    <version>1</version>\n");
    let _ = writeln!(x, "    <type>{DEVICE_TYPE}</type>");
    x.push_str("    <device>\n        <name>TT LCD CL-W383</name>\n        <id>0</id>\n        <layout>\n");
    let _ = writeln!(x, "            <led_count>{LED_COUNT}</led_count>");
    let _ = writeln!(x, "            <size>\n                <width>{LED_COUNT}</width>\n                <height>1</height>\n            </size>");
    x.push_str("            <led_name>\n");
    for i in 0..LED_COUNT {
        let _ = writeln!(x, "                <led>LCD {}</led>", i + 1);
    }
    x.push_str("            </led_name>\n        </layout>\n        <supported_effect>\n");
    for e in &EFFECTS {
        x.push_str("            <effect>\n");
        let _ = writeln!(x, "                <name>{}</name>", e.name);
        let _ = writeln!(x, "                <id>{}</id>", e.id);
        let _ = writeln!(x, "                <synchronizable>{}</synchronizable>", e.synchronizable);
        let _ = writeln!(x, "                <customized_color>{}</customized_color>", e.customized_color);
        if e.speed_levels > 0 {
            let _ = writeln!(x, "                <speed_supported>1<levels>{}</levels><default>1</default></speed_supported>", e.speed_levels);
        } else {
            x.push_str("                <speed_supported>0</speed_supported>\n");
        }
        x.push_str("                <direction_supported>0</direction_supported>\n");
        x.push_str("            </effect>\n");
    }
    x.push_str("        </supported_effect>\n        <model>Thermaltake CL-W383 LCD</model>\n    </device>\n</root>\n");
    x
}

#[cfg(test)]
mod tests {
    /// capability.golden.xml is what the C# plugin returns (generated by running its GetCapability under Mono).
    #[test]
    fn identical_to_the_csharp_plugin() {
        // (a CRLF checkout of the fixture must not matter)
        assert_eq!(super::capability_xml(), include_str!("capability.golden.xml").replace("\r\n", "\n"));
    }
}
